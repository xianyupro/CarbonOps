def get_catalog_models() -> list[dict]:
    """返回 120 个模型的完整 spec 列表（已映射为英文枚举）。

    每个 dict 含: name, code, industry, functionType, processStage,
                  description, tags, status, stage, provider, sourceCode,
                  pythonVersion, accuracy
    """
    result: list[dict] = []
    provider_seq: dict[str, int] = {}
    provider_abbr = {
        "中南大学": "CSU",
        "大连理工大学": "DUT",
        "华东理工大学": "ECUST",
        "浙江大学": "ZJU",
        "东北大学": "NEU",
    }
    for (name, industry, process_stage, ft_cn, dev_status_cn,
         description, provider) in _RAW_MODELS:
        abbr = provider_abbr.get(provider, "GEN")
        provider_seq[abbr] = provider_seq.get(abbr, 0) + 1
        code = f"{abbr}_{provider_seq[abbr]:03d}"

        ft = FUNCTION_TYPE_MAP[ft_cn]
        status, stage = DEV_STATUS_MAP[dev_status_cn]

        # 基于功能类型和状态生成合理的准确率
        if status == "ONLINE":
            accuracy = round(0.85 + (hash(name) % 140) / 1000.0, 3)
        else:
            accuracy = 0.0

        result.append({
            "name": name,
            "code": code,
            "industry": industry,
            "functionType": ft,
            "processStage": process_stage,
            "description": description,
            "tags": [ft_cn, industry],
            "status": status,
            "stage": stage,
            "provider": provider,
            "accuracy": accuracy,
            "pythonVersion": "3.11",
            "sourceCode": _gen_source_code(name, ft, description, process_stage, provider),
        })
    return result
