def scholar_names() -> list[str]:
    return list(SCHOLAR.keys())


def apply_scholar_content(mm) -> bool:
    """按名称匹配并把学术内容写入元模型 ORM 对象（幂等）。返回是否命中。"""
    entry = SCHOLAR.get(mm.name)
    if not entry:
        return False
    for field in _SCHOLAR_FIELDS:
        if field in entry:
            setattr(mm, field, entry[field])
    return True
